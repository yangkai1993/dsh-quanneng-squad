import { readFileSync, writeFileSync, existsSync, mkdirSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { W, runGate, failFast } from './lib/gate-kit.mjs';

// 多宿主适配器生成层（五期 1.19.0 · G1 依据 wshobson 一源七宿主 + Invariants「生成物不手改」）：
// 输入=canonical 真源（presets.yml 预设名清单 + assets/skills/*/SKILL.md frontmatter）；
// 输出=dist-adapters/<宿主>/（Claude Code marketplace 形态为主）；
// 铁律：本脚本是唯一写手，产物带指纹头；canonical 改后重跑即同步（与 build-patch 同范式）。
const PKGDIR = join(dirname(fileURLToPath(import.meta.url)), '..');
const MARK = '<!-- AUTO-GENERATED by scripts/build-adapters.mjs from canonical truth — DO NOT HAND-EDIT -->';

// 读 presets.yml 的预设 id 集（不引 YAML 依赖：正则抽 id: squad-*，与 build-patch 同口径）
function presetIds() {
  const src = readFileSync(join(PKGDIR, 'assets/canonical/presets.yml'), 'utf8');
  return [...new Set([...src.matchAll(/id:\s*(squad-[\w-]+)/g)].map(m => m[1]))];
}

// 读 skills frontmatter（name/description）
function skills() {
  const dir = join(PKGDIR, 'assets/skills');
  if (!existsSync(dir)) return [];
  const out = [];
  for (const n of readdirSync(dir)) {
    const p = join(dir, n, 'SKILL.md');
    if (!existsSync(p)) continue;
    const t = readFileSync(p, 'utf8');
    const name = (t.match(/^name:\s*(.+)$/m) || [])[1] || n;
    const desc = (t.match(/^description:\s*(.+)$/m) || [])[1] || '';
    out.push({ dir: n, name, desc });
  }
  return out;
}

// Claude Code 插件形态：plugin.json + marketplace.json + commands/*.md + agents/*.md
function buildClaudeAdapter({ version }) {
  const out = {};
  out['plugin.json'] = JSON.stringify({
    name: 'dsh-quanneng-squad',
    description: '全能编程小队：16 席位朝廷制多智能体编排（Event Sourcing 轮次真源 + 11 门机器门禁）',
    version,
    author: { name: 'YG / squad-lead' },
    keywords: ['multi-agent', 'orchestration', 'squad', 'governance'],
  }, null, 2);
  out['marketplace.json'] = JSON.stringify({
    name: 'quanneng-squad-marketplace',
    owner: { name: 'dsh-quanneng-squad' },
    metadata: { description: '全能编程小队插件分发清单（生成物）', version },
    plugins: [{
      name: 'dsh-quanneng-squad', source: './', description: '全能编程小队', version, category: 'multi-agent',
    }],
  }, null, 2);
  // commands：12 技能 → /squad:<name>
  for (const s of skills()) {
    const body = readFileSync(join(PKGDIR, 'assets/skills', s.dir, 'SKILL.md'), 'utf8');
    const bodyNoFm = body.replace(/^---[\s\S]*?---\n/, '');
    out['commands/' + s.dir + '.md'] = MARK + '\n\n' +
      '---\n' +
      'description: ' + s.desc + '\n' +
      'argument-hint: (可选参数)\n' +
      '---\n\n' + bodyNoFm.trim();
  }
  // agents：7 预设 → Claude agent md（frontmatter name/description；工具面省略——canonical 是唯一工具真源）
  for (const id of presetIds()) {
    const label = id.replace(/^squad-/, '');
    out['agents/' + id + '.md'] = MARK + '\n\n' +
      '---\n' +
      'name: ' + id + '\n' +
      'description: 全能编程小队预设 ' + label + '（真源 assets/canonical/presets.yml id=' + id + '；本文件为 Claude 形态投影，工具面以 canonical 为准）\n' +
      '---\n\n' +
      '# ' + id + '\n\n' +
      '全能编程小队成员预设（' + label + '）。派活须携带 TK 令牌与六要素任务书；回报回主对话。真源文件：packages/dsh-quanneng-squad/assets/canonical/presets.yml。';
  }
  return out;
}

// 主入口：写 dist-adapters/。返回 {hostFiles, count}
export function buildAdapters({ version } = {}) {
  const v = version || JSON.parse(readFileSync(join(PKGDIR, 'package.json'), 'utf8')).version;
  const claude = buildClaudeAdapter({ version: v });
  const root = join(PKGDIR, 'dist-adapters', 'claude-code');
  let count = 0;
  for (const [rel, content] of Object.entries(claude)) {
    const p = join(root, rel);
    mkdirSync(dirname(p), { recursive: true });
    writeFileSync(p, content + (content.endsWith('\n') ? '' : '\n'), 'utf8');
    count++;
  }
  return { root, count, version: v };
}

// 门：产物存在+全部带指纹头+skills 全部导出（防孤儿）
export function checkAdapters() {
  const problems = [];
  const root = join(PKGDIR, 'dist-adapters', 'claude-code');
  if (!existsSync(root)) problems.push('dist-adapters/claude-code 缺失（跑 build-adapters.mjs）');
  else {
    const want = skills().length;
    const cmds = join(root, 'commands');
    const have = existsSync(cmds) ? readdirSync(cmds).filter(f => f.endsWith('.md')).length : 0;
    if (have < want) problems.push('commands 导出不全: ' + have + '/' + want);
    for (const f of walkFiles(root)) {
      const t = readFileSync(f, 'utf8');
      if (t.endsWith('.md') && !t.startsWith(MARK)) problems.push('产物缺指纹头（疑似手改）: ' + f.split('dist-adapters')[1]);
    }
  }
  const gate = runGate({ name: 'adapters', varName: 'QUANNENG_ALLOW_ADAPTER_GAP',
    kind: '适配器产物缺口: ' + problems.join('；'), items: problems, W,
    report: { workspace: W, problems } });
  failFast(gate);
  return { exit: gate, problems };
}
function walkFiles(d) { let o = []; for (const e of readdirSync(d, { withFileTypes: true })) { const p = join(d, e.name); if (e.isDirectory()) o = o.concat(walkFiles(p)); else o.push(p); } return o; }

if (process.argv[1] && import.meta.url.endsWith(process.argv[1].split(/[\\/]/).pop())) {
  console.log(JSON.stringify(process.argv.includes('--check') ? checkAdapters() : buildAdapters(), null, 2));
}
